"""Earmark logo (2026-11-25, v3): a marigold bookmark crossed by one smooth voice wave. The wave is cream on
the background and cut through the bookmark where it crosses it: a mark placed on the sound. Distinct from
the owner's other apps (no folds, no moon, no bar chart).

Writes every logo and icon file from one geometry (run from the repo root, Chrome installed):
    python docs/brand/make_logo.py
"""
import math
import subprocess
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / 'docs/brand'
RES = ROOT / 'app/android/app/src/main/res/drawable'
IOS = ROOT / 'app/ios/Runner/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png'
CHROME = r'C:\Program Files\Google\Chrome\Application\chrome.exe'

CARBON, CREAM, MARIGOLD = '#14130F', '#F3EEE2', '#FFC23D'
CX = 512
BW, TOP, BOT, NOTCH, RADIUS = 270, 210, 812, 100, 40     # bookmark
WAVE_Y, AMP, CYCLES, STROKE = 540, 66, 2.5, 40           # voice wave


def bookmark():
    x0, x1 = CX - BW / 2, CX + BW / 2
    r = RADIUS
    return (f'M{x0},{TOP + r} A{r},{r} 0 0 1 {x0 + r},{TOP} H{x1 - r} A{r},{r} 0 0 1 {x1},{TOP + r} '
            f'V{BOT} L{CX},{BOT - NOTCH} L{x0},{BOT} Z')


def wave(n=120):
    pts = []
    for i in range(n + 1):
        t = i / n
        env = math.sin(math.pi * t) ** 1.6
        pts.append((150 + 724 * t, WAVE_Y + AMP * env * math.sin(2 * math.pi * CYCLES * t + math.pi)))
    return 'M' + ' L'.join(f'{x:.1f},{y:.1f}' for x, y in pts)


def svg_icon(full_bleed=True):
    bk, wv = bookmark(), wave()
    bg = '<rect width="1024" height="1024" fill="url(#g)"/>' if full_bleed else ''
    cut = CARBON if full_bleed else CARBON
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" '
            f'aria-label="Earmark logo: a bookmark crossed by a voice wave">'
            f'<defs><radialGradient id="g" cx="512" cy="520" r="620" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="#2D2617"/><stop offset=".55" stop-color="#1A1813"/>'
            f'<stop offset="1" stop-color="{CARBON}"/></radialGradient>'
            f'<linearGradient id="r" x1="0" y1="{TOP}" x2="0" y2="{BOT}" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="#FFD766"/><stop offset="1" stop-color="#F2A21A"/></linearGradient>'
            f'<clipPath id="k"><path d="{bk}"/></clipPath></defs>{bg}'
            f'<path d="{wv}" fill="none" stroke="{CREAM}" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<path d="{bk}" fill="url(#r)"/>'
            f'<path d="{wv}" fill="none" stroke="{cut}" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round" clip-path="url(#k)"/>'
            '</svg>')


def svg_mono():
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" aria-label="Earmark">'
            f'<path d="{wave()}" fill="none" stroke="currentColor" stroke-width="{STROKE}" stroke-linecap="round"/>'
            f'<path d="{bookmark()}" fill="currentColor"/></svg>')


def vector(body, size_dp, viewport, group=''):
    """A VectorDrawable; `body` holds the inner elements (paths, nested groups)."""
    lines = '\n'.join(f'        {e}' for e in body)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by docs/brand/make_logo.py: edit the script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp" '
            f'android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f'    <group {group}>\n{lines}\n    </group>\n</vector>\n')


def fill(color, data):
    return f'<path android:fillColor="{color}" android:pathData="{data}"/>'


def stroke(color, data):
    return (f'<path android:strokeColor="{color}" android:strokeWidth="{STROKE}" android:strokeLineCap="round" '
            f'android:strokeLineJoin="round" android:pathData="{data}"/>')


def android():
    bk, wv = bookmark(), wave()
    # Adaptive icon: 108 dp canvas, 72 dp visible; the 1024 artwork maps onto the visible 72 dp.
    fit = 'android:scaleX="0.0703" android:scaleY="0.0703" android:translateX="18" android:translateY="18"'
    cut = f'<group><clip-path android:pathData="{bk}"/>{stroke(CARBON, wv)}</group>'
    (RES / 'ic_launcher_foreground.xml').write_text(
        vector([stroke(CREAM, wv), fill(MARIGOLD, bk), cut], 108, 108, fit), encoding='utf-8')
    one = [stroke('#FFFFFF', wv), fill('#FFFFFF', bk)]
    (RES / 'ic_launcher_monochrome.xml').write_text(vector(one, 108, 108, fit), encoding='utf-8')
    # Status bar, notification actions, Quick Settings tile (24 dp): same shape, one colour, a bit larger.
    (RES / 'ic_stat_earmark.xml').write_text(
        vector(one, 24, 1024, 'android:scaleX="1.25" android:scaleY="1.25" android:pivotX="512" android:pivotY="512"'),
        encoding='utf-8')


def render(svg, size, out, rgb=False):
    with tempfile.TemporaryDirectory() as tmp:
        src, png = Path(tmp, 'logo.svg'), Path(tmp, 'logo.png')
        src.write_text(svg, encoding='utf-8')
        subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--hide-scrollbars',
                        '--force-device-scale-factor=1', '--default-background-color=00000000',
                        '--window-size=1024,1024', f'--screenshot={png}', src.as_uri()],
                       check=True, capture_output=True, timeout=90)
        img = Image.open(png).convert('RGB' if rgb else 'RGBA')
        img.resize((size, size), Image.LANCZOS).save(out)
    print(out)


if __name__ == '__main__':
    (BRAND / 'logo.svg').write_text(svg_icon(), encoding='utf-8')
    (BRAND / 'logo-mark.svg').write_text(svg_icon(full_bleed=False), encoding='utf-8')
    (BRAND / 'logo-mono.svg').write_text(svg_mono(), encoding='utf-8')
    android()
    render(svg_icon(), 1024, BRAND / 'icon-1024.png', rgb=True)
    render(svg_icon(), 512, BRAND / 'play-icon-512.png', rgb=True)
    render(svg_icon(full_bleed=False), 1024, BRAND / 'logo-mark-1024.png')
    render(svg_icon(), 1024, IOS, rgb=True)  # iOS: square, no transparency (the system rounds it)
